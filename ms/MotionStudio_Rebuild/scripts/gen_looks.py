#!/usr/bin/env python3
"""Bakes Motion Studio's bundled looks into `.cube` 3D LUTs.

The look maths is written here (GPL-3.0-or-later, same as the project) so the
app ships no third-party LUT files with unclear licensing. Output goes to
`android/app/src/main/assets/looks/` next to the Kotlin UI that lists them.

Usage: python3 scripts/gen_looks.py [--size 17]
"""
from __future__ import annotations

import argparse
import math
import pathlib

OUT_DIR = pathlib.Path(__file__).resolve().parent.parent / "android/app/src/main/assets/looks"


def clamp(v: float) -> float:
    return 0.0 if v < 0.0 else 1.0 if v > 1.0 else v


def luma(r: float, g: float, b: float) -> float:
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def saturate(rgb, amount: float):
    r, g, b = rgb
    y = luma(r, g, b)
    return (
        clamp(y + (r - y) * amount),
        clamp(y + (g - y) * amount),
        clamp(y + (b - y) * amount),
    )


def contrast(rgb, amount: float):
    return tuple(clamp((c - 0.5) * amount + 0.5) for c in rgb)


def lift_gamma_gain(rgb, lift: float, gamma: float, gain: float):
    out = []
    for c in rgb:
        v = clamp(c + lift)
        v = gain * (v ** (1.0 / gamma)) if v > 0.0 else 0.0
        out.append(clamp(v))
    return tuple(out)


def teal_orange(rgb):
    r, g, b = contrast(rgb, 1.12)
    y = luma(r, g, b)
    shadow = (1.0 - y) ** 2
    high = y ** 2
    r = r + 0.05 * high - 0.03 * shadow
    g = g + 0.01 * high + 0.02 * shadow
    b = b + 0.09 * shadow - 0.06 * high
    return saturate((clamp(r), clamp(g), clamp(b)), 1.1)


def bleach_bypass(rgb):
    r, g, b = saturate(rgb, 0.35)
    r, g, b = contrast((r, g, b), 1.35)
    return lift_gamma_gain((r, g, b), -0.01, 1.05, 1.03)


def warm_film(rgb):
    r, g, b = lift_gamma_gain(rgb, 0.012, 1.06, 1.0)
    r = clamp(r * 1.06 + 0.01)
    g = clamp(g * 1.01 + 0.005)
    b = clamp(b * 0.94)
    return saturate((r, g, b), 1.05)


def cool_noir(rgb):
    r, g, b = saturate(rgb, 0.18)
    r, g, b = contrast((r, g, b), 1.28)
    r = clamp(r * 0.96)
    g = clamp(g * 0.99)
    b = clamp(b * 1.08 + 0.01)
    return lift_gamma_gain((r, g, b), -0.005, 1.02, 1.0)


def vivid_punch(rgb):
    r, g, b = contrast(rgb, 1.14)
    return saturate((r, g, b), 1.45)


def fade_matte(rgb):
    r, g, b = saturate(rgb, 0.8)
    r = 0.06 + r * 0.88
    g = 0.06 + g * 0.88
    b = 0.07 + b * 0.87
    return contrast((clamp(r), clamp(g), clamp(b)), 0.94)


LOOKS = [
    ("teal_orange", "Teal & Orange", "Blockbuster split tone", teal_orange),
    ("bleach_bypass", "Bleach Bypass", "Silver-halide contrast", bleach_bypass),
    ("warm_film", "Warm Film", "Golden hour warm-up", warm_film),
    ("cool_noir", "Cool Noir", "Desaturated blue crush", cool_noir),
    ("vivid_punch", "Vivid Punch", "Social-ready saturation", vivid_punch),
    ("fade_matte", "Fade Matte", "Lifted blacks, soft whites", fade_matte),
]


def write_cube(name: str, title: str, fn, size: int) -> pathlib.Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{name}.cube"
    lines = [
        "# Generated by Motion Studio scripts/gen_looks.py - GPL-3.0-or-later",
        "# Authored in-repo; no third-party LUT data is redistributed.",
        f'TITLE "{title}"',
        f"LUT_3D_SIZE {size}",
        "DOMAIN_MIN 0.0 0.0 0.0",
        "DOMAIN_MAX 1.0 1.0 1.0",
    ]
    step = 1.0 / (size - 1)
    for bi in range(size):
        for gi in range(size):
            for ri in range(size):
                out = fn((ri * step, gi * step, bi * step))
                lines.append(f"{out[0]:.6f} {out[1]:.6f} {out[2]:.6f}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=17)
    args = ap.parse_args()
    if args.size < 2 or args.size > 64:
        raise SystemExit("size must be 2..64")
    for name, title, _desc, fn in LOOKS:
        p = write_cube(name, title, fn, args.size)
        print(f"{p.relative_to(p.parents[3])}  {p.stat().st_size // 1024} KiB")


if __name__ == "__main__":
    main()
